package Variables;

public class Variables {
   public static void main(String[] args) {

      //INT
       int age=20;
       System.out.println("Your are age is "+ age);

       int y; // Declaration
       y=20; //Intialiation
       System.out.println(y);

       //DOUBLE
       double price=12.30;
       System.out.println("Your Pizza price is $"+ price);

       //CHAR
       char Grade='A';
       System.out.println("Your Maths grade is "+ Grade);

       //BOOLEAN
       boolean IsStudent=true;
       System.out.println(IsStudent);

       //STRING
       String Animal="Wolf";
       System.out.println("Your Fav Animal is "+ Animal);

    }
}